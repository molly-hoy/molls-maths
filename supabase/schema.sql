-- ==========================================================================
-- Moll's Maths: accounts, students, consent and access rules for Supabase
-- --------------------------------------------------------------------------
-- HOW TO USE: in the Supabase dashboard open SQL Editor, paste this whole
-- file and press Run. Run it once on a new project.
--
-- WHAT IT SETS UP
--   • profiles: one row per adult account (parent, teacher or tutor).
--     Supabase Auth keeps the login itself; this table keeps the rest,
--     including when the privacy notice was accepted.
--   • students: the pupils an adult account looks after. Each pupil also
--     has a login (a Supabase Auth user) whose username and password the
--     website generates. A pupil can read only their own record.
--   • Row Level Security (RLS) on both tables, so an adult sees only their
--     own pupils and logged-out visitors can't read either table.
--
-- Table access is granted explicitly (the "grant" lines) because the
-- Supabase setting "Grant API access to new tables automatically" is off.
--
-- Creating and removing pupil logins needs a secret key, so that work is
-- done by the "student-accounts" Edge Function, never by the website.
-- ==========================================================================


-- ---------- 1. Adult accounts ----------
create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text not null default '' check (char_length(display_name) <= 80),
  account_type text not null default 'parent'
    check (account_type in ('parent', 'teacher', 'tutor')),
  privacy_version text,                 -- which version of the privacy notice they accepted
  privacy_accepted_at timestamptz,      -- when they accepted it (set by the server)
  created_at timestamptz not null default now()
);

-- When an adult signs up, make their profile row automatically.
-- Pupil logins (account_type 'student') get no profile row: their access
-- comes from their row in the students table instead.
-- "security definer" lets this run before the new user has any permissions.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  kind text := coalesce(new.raw_user_meta_data ->> 'account_type', 'parent');
begin
  if kind = 'student' then
    return new;
  end if;

  insert into public.profiles (id, display_name, account_type, privacy_version, privacy_accepted_at)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'display_name', ''),
    case when kind in ('parent', 'teacher', 'tutor') then kind else 'parent' end,
    new.raw_user_meta_data ->> 'privacy_version',
    case when new.raw_user_meta_data ->> 'privacy_version' is not null then now() end
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();


-- ---------- 2. Pupils ----------
create table if not exists public.students (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.profiles (id) on delete cascade,
  first_name text not null check (char_length(first_name) between 1 and 40),
  last_name text not null check (char_length(last_name) between 1 and 40),
  year_group integer not null check (year_group between 7 and 13),
  -- Generated by the website: first 3 letters of the first name plus first 3
  -- letters of the surname, in lower case. A number is added if it's taken.
  username text not null unique check (username ~ '^[a-z0-9]{2,30}$'),
  -- The pupil's own login. Deleted together with the pupil.
  auth_user_id uuid unique references auth.users (id) on delete cascade,
  -- When the adult confirmed they were entitled to add this pupil.
  consent_confirmed_at timestamptz not null,
  created_at timestamptz not null default now()
);

create index if not exists students_owner_idx on public.students (owner_id);


-- ---------- 3. Row Level Security: switch it on ----------
alter table public.profiles enable row level security;
alter table public.students enable row level security;


-- ---------- 4. Rules: who may do what ----------
-- (select auth.uid()) is the id of the logged-in user. It is empty for
-- logged-out visitors, so they match nothing.

-- Profiles: an adult reads and updates only their own profile.
create policy "Read own profile"
  on public.profiles for select to authenticated
  using (id = (select auth.uid()));

create policy "Update own profile"
  on public.profiles for update to authenticated
  using (id = (select auth.uid()))
  with check (id = (select auth.uid()));

-- Students: an adult reads their own pupils. Pupils aren't allowed to
-- change their own record. Adding and removing pupils is done by the
-- Edge Function, so there are no insert or delete rules here.
create policy "Adults read own students"
  on public.students for select to authenticated
  using (owner_id = (select auth.uid()));

create policy "Pupils read own record"
  on public.students for select to authenticated
  using (auth_user_id = (select auth.uid()));


-- ---------- 5. Table permissions (the "grant" step) ----------
-- Only logged-in users get any access. Logged-out visitors ("anon") get none.
grant select on public.profiles to authenticated;
grant update (display_name) on public.profiles to authenticated;   -- only the name can be changed
grant select on public.students to authenticated;
-- Note: no grant to "anon" on purpose, and no insert/update/delete on students
-- for website users: the Edge Function does those with the secret key.
